/** SundarTV's own symbols (Material Symbols as white PNGs), tinted with the text color through a mask. */
const SYMBOLS = import.meta.glob('../assets/symbols/*.png', { eager: true, query: '?url', import: 'default' }) as Record<string, string>;

export type SymbolName =
  | 'sunny'
  | 'clear_night'
  | 'partly_cloudy_day'
  | 'partly_cloudy_night'
  | 'cloud'
  | 'foggy'
  | 'rainy'
  | 'snowflake'
  | 'thunderstorm'
  | 'sunrise'
  | 'sunset'
  | 'bitcoin'
  | 'sparkles';

export function Symbol({ name, size = '1em' }: { name: SymbolName; size?: string }) {
  const url = SYMBOLS[`../assets/symbols/${name}.png`];
  return (
    <span
      className="symbol"
      aria-hidden="true"
      style={{ width: size, height: size, WebkitMaskImage: `url(${url})`, maskImage: `url(${url})` }}
    />
  );
}

export function weatherSymbol(code: number, isDay: boolean): SymbolName {
  if (code <= 1) return isDay ? 'sunny' : 'clear_night';
  if (code === 2) return isDay ? 'partly_cloudy_day' : 'partly_cloudy_night';
  if (code === 3) return 'cloud';
  if (code === 45 || code === 48) return 'foggy';
  if ((code >= 71 && code <= 77) || code === 85 || code === 86) return 'snowflake';
  if (code >= 95) return 'thunderstorm';
  if (code >= 51) return 'rainy';
  return 'cloud';
}

type Brand = { title: string; hex: string; path: string };
const BRANDS = brand as Record<string, Brand>;

export function brandIcon(slug: string | null): Brand | null {
  if (!slug) return null;
  return BRANDS[slug] ?? null;
}

/** A Simple Icons mark (CC0) in the current color. */
export function BrandMark({ slug, size, color }: { slug: string; size: string; color?: string }) {
  const b = brandIcon(slug);
  if (!b) return null;
  return (
    <svg viewBox="0 0 24 24" style={{ width: size, height: size }} aria-hidden="true" className="brand-mark">
      <path d={b.path} fill={color ?? 'currentColor'} />
    </svg>
  );
}
